// smppStatusName resolves a command_status wire value to its legacy
// CommandStatus name, reproducing CommandStatusEncoder._decode: a value in the
// discrete map yields its name; otherwise the SMPP reserved ranges apply — below
// 0x100 an unknown low status, 0x100-0x3FF an SMPP extension, 0x400-0x4FF an
// SMSC vendor-specific error, and 0x500 and above a general reserved status.
// Matching the exact name matters: the error-retry policy keys retry rules off
// it and it is published as the DLR status.
func smppStatusName(status uint32) string {
	if name, ok := commandStatusNames[status]; ok {
		return name
	}
	switch {
	case status < 0x100:
		return "RESERVEDSTATUS_UNKNOWN_STATUS"
	case status <= 0x3FF:
		return "RESERVEDSTATUS_SMPP_EXTENSION"
	case status <= 0x4FF:
		return "RESERVEDSTATUS_VENDOR_SPECIFIC"
	default:
		return "RESERVEDSTATUS"
	}
}
